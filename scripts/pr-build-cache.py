#!/usr/bin/env python3
"""Cache package archives between verification runs of the same pull request.

Only archives whose package recipe tree and transitive build-dependency trees
are unchanged are restored. This lets a PR retry only the packages that failed
or were invalidated by a recipe/dependency change.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ARCHIVE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._+-]*\.nawa\.tar\.zst$")
MANIFEST_NAME = "manifest.json"
MANIFEST_SCHEMA = 1


class CacheError(Exception):
    pass


@dataclass(frozen=True)
class Recipe:
    name: str
    archive: str
    directory: Path
    data: dict[str, Any]


def file_tree_hash(directory: Path) -> str:
    """Hash every file and relative path in a recipe directory, including assets."""
    digest = hashlib.sha256()
    for path in sorted(directory.rglob("*")):
        if not path.is_file() and not path.is_symlink():
            continue
        relative = path.relative_to(directory).as_posix().encode("utf-8")
        digest.update(relative)
        digest.update(b"\0")
        if path.is_symlink():
            payload = os.readlink(path).encode("utf-8")
        else:
            payload = path.read_bytes()
        digest.update(len(payload).to_bytes(8, "big"))
        digest.update(payload)
    return digest.hexdigest()


def load_recipes(root: Path) -> dict[str, Recipe]:
    recipes: dict[str, Recipe] = {}
    for recipe_file in sorted(root.glob("*/*/recipe.toml")):
        try:
            data = tomllib.loads(recipe_file.read_text(encoding="utf-8"))
            package = data["package"]
            name = str(package["name"])
            version = str(package["version"])
            rel = str(package.get("rel", 1))
        except (OSError, KeyError, TypeError, tomllib.TOMLDecodeError) as exc:
            raise CacheError(f"cannot read package metadata from {recipe_file}: {exc}") from exc
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._+-]*", name):
            raise CacheError(f"unsafe package name in {recipe_file}: {name!r}")
        archive = f"{name}-{version}-{rel}.nawa.tar.zst"
        if not ARCHIVE_RE.fullmatch(archive):
            raise CacheError(f"unsafe archive name generated by {recipe_file}: {archive!r}")
        if name in recipes:
            raise CacheError(f"duplicate recipe name: {name}")
        recipes[name] = Recipe(name, archive, recipe_file.parent, data)
    return recipes


def build_keys(recipes: dict[str, Recipe]) -> dict[str, str]:
    """Include the recipe tree and recursive build dependencies in each cache key."""
    memo: dict[str, str] = {}
    active: set[str] = set()

    def calculate(name: str) -> str:
        if name in memo:
            return memo[name]
        recipe = recipes.get(name)
        if recipe is None:
            return hashlib.sha256(f"external:{name}".encode("utf-8")).hexdigest()
        if name in active:
            # Recipe validation catches dependency cycles; keep cache calculation
            # deterministic rather than recursing forever if a broken tree appears.
            return hashlib.sha256(f"dependency-cycle:{name}".encode("utf-8")).hexdigest()

        active.add(name)
        digest = hashlib.sha256()
        digest.update(name.encode("utf-8"))
        digest.update(b"\0")
        digest.update(recipe.archive.encode("utf-8"))
        digest.update(b"\0")
        digest.update(file_tree_hash(recipe.directory).encode("ascii"))

        depends = recipe.data.get("depends", {})
        build_deps = depends.get("build", []) if isinstance(depends, dict) else []
        if isinstance(build_deps, str):
            build_deps = [build_deps]
        for dependency in sorted({str(item) for item in build_deps}):
            digest.update(b"\0build-dependency\0")
            digest.update(dependency.encode("utf-8"))
            digest.update(b"\0")
            digest.update(calculate(dependency).encode("ascii"))

        active.remove(name)
        memo[name] = digest.hexdigest()
        return memo[name]

    for name in sorted(recipes):
        calculate(name)
    return memo


def read_manifest(cache_dir: Path) -> list[dict[str, str]]:
    path = cache_dir / MANIFEST_NAME
    if not path.is_file():
        return []
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
        if value.get("schema") != MANIFEST_SCHEMA or not isinstance(value.get("packages"), list):
            raise ValueError("unsupported manifest schema")
        return value["packages"]
    except (OSError, ValueError, AttributeError, TypeError) as exc:
        print(f"::warning::ignoring invalid pull request package cache manifest: {exc}", file=sys.stderr)
        return []


def valid_entry(
    entry: dict[str, Any],
    recipes: dict[str, Recipe],
    keys: dict[str, str],
    cache_dir: Path,
) -> tuple[Recipe, Path] | None:
    name = entry.get("name")
    archive = entry.get("archive")
    key = entry.get("build_key")
    if not isinstance(name, str) or not isinstance(archive, str) or not isinstance(key, str):
        return None
    if Path(archive).name != archive or not ARCHIVE_RE.fullmatch(archive):
        return None
    recipe = recipes.get(name)
    if recipe is None or recipe.archive != archive or keys.get(name) != key:
        return None
    cached = cache_dir / archive
    if not cached.is_file() or cached.stat().st_size == 0:
        return None
    return recipe, cached


def restore_cache(recipes_root: Path, cache_dir: Path, out_dir: Path) -> tuple[int, int]:
    recipes = load_recipes(recipes_root)
    keys = build_keys(recipes)
    cache_dir.mkdir(parents=True, exist_ok=True)
    out_dir.mkdir(parents=True, exist_ok=True)
    restored = 0
    rejected = 0

    for entry in read_manifest(cache_dir):
        checked = valid_entry(entry, recipes, keys, cache_dir)
        if checked is None:
            rejected += 1
            continue
        recipe, cached = checked
        target = out_dir / recipe.archive
        if target.exists():
            continue
        shutil.copy2(cached, target)
        restored += 1

    return restored, rejected


def save_cache(
    recipes_root: Path,
    cache_dir: Path,
    out_dir: Path,
    since_file: Path,
) -> tuple[int, int]:
    recipes = load_recipes(recipes_root)
    keys = build_keys(recipes)
    cache_dir.mkdir(parents=True, exist_ok=True)
    out_dir.mkdir(parents=True, exist_ok=True)
    try:
        since_ns = since_file.stat().st_mtime_ns
    except OSError as exc:
        raise CacheError(f"build start marker is missing: {since_file}") from exc

    entries: dict[str, dict[str, str]] = {}
    for entry in read_manifest(cache_dir):
        checked = valid_entry(entry, recipes, keys, cache_dir)
        if checked is None:
            continue
        recipe, _ = checked
        entries[recipe.name] = {
            "name": recipe.name,
            "archive": recipe.archive,
            "build_key": keys[recipe.name],
        }

    added = 0
    for archive_path in sorted(out_dir.glob("*.nawa.tar.zst")):
        if not archive_path.is_file() or archive_path.stat().st_mtime_ns <= since_ns:
            continue
        recipe = next((item for item in recipes.values() if item.archive == archive_path.name), None)
        if recipe is None:
            continue
        target = cache_dir / recipe.archive
        shutil.copy2(archive_path, target)
        entries[recipe.name] = {
            "name": recipe.name,
            "archive": recipe.archive,
            "build_key": keys[recipe.name],
        }
        added += 1

    live_archives = {entry["archive"] for entry in entries.values()}
    for cached in cache_dir.glob("*.nawa.tar.zst"):
        if cached.name not in live_archives:
            cached.unlink()

    manifest = {
        "schema": MANIFEST_SCHEMA,
        "packages": [entries[name] for name in sorted(entries)],
    }
    temp = cache_dir / f".{MANIFEST_NAME}.tmp"
    temp.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    temp.replace(cache_dir / MANIFEST_NAME)
    return added, len(entries)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("restore", "save"):
        command = sub.add_parser(name)
        command.add_argument("--recipes", type=Path, required=True)
        command.add_argument("--cache-dir", type=Path, required=True)
        command.add_argument("--out-dir", type=Path, required=True)
        if name == "save":
            command.add_argument("--since", type=Path, required=True)
    args = parser.parse_args(argv)

    try:
        if args.command == "restore":
            restored, rejected = restore_cache(args.recipes, args.cache_dir, args.out_dir)
            print(f"PR package cache: restored {restored} archive(s); rejected {rejected} stale or invalid entrie(s).")
        else:
            added, total = save_cache(args.recipes, args.cache_dir, args.out_dir, args.since)
            print(f"PR package cache: saved {added} new archive(s); {total} reusable archive(s) retained.")
        return 0
    except (CacheError, OSError) as exc:
        print(f"::error::PR package cache: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
