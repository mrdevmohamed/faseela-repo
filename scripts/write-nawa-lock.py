#!/usr/bin/env python3
"""scripts/write-nawa-lock.py — write the distribution's bootstrap Nawa source
lock (bootstrap/nawa-source.toml) from THIS repository's nawa recipe.

The distribution tooling (github.com/mrdevmohamed/faseela) rewrites the nawa
recipe from its own lock before building. When a package build runs here, the
recipe in this repository must win, otherwise a pin bump (pin-nawa-source.py)
is silently reverted to the lock's older release, the build reports "up to
date", and publishing fails for the missing archive.

    python3 scripts/write-nawa-lock.py <distro checkout>
"""
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECIPE = ROOT / "recipes" / "base" / "nawa" / "recipe.toml"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    pkg = tomllib.loads(RECIPE.read_text(encoding="utf-8"))["package"]
    m = re.fullmatch(r"https://github\.com/([^/]+/[^/]+)/archive/([0-9a-f]{40})\.tar\.gz",
                     pkg["source"])
    if not m:
        sys.exit(f"write-nawa-lock: unexpected nawa source URL {pkg['source']!r}")
    if not re.fullmatch(r"[0-9a-f]{64}", pkg["sha256"]):
        sys.exit("write-nawa-lock: nawa sha256 is not a 64-hex digest")
    lock = Path(sys.argv[1]) / "bootstrap" / "nawa-source.toml"
    lock.write_text(
        "# Generated by faseela-repo scripts/write-nawa-lock.py from its nawa recipe.\n"
        "schema = 1\n"
        f'repository = "{m.group(1)}"\n'
        f'version = "{pkg["version"]}"\n'
        f'rel = {int(pkg["rel"])}\n'
        f'commit = "{m.group(2)}"\n'
        f'sha256 = "{pkg["sha256"]}"\n',
        encoding="utf-8")
    print(f"write-nawa-lock: {lock} <- nawa {pkg['version']}-{pkg['rel']} ({m.group(2)[:7]})")


main()
