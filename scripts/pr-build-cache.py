#!/usr/bin/env python3
"""Cache package archives between verification runs of the same pull request.

Only archives whose package recipe tree and transitive build-dependency trees
are unchanged are restored. This lets a PR retry only the packages that failed
or were invalidated by a recipe/dependency change.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ARCHIVE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._+-]*\.nawa\.tar\.zst$")
MANIFEST_NAME = "manifest.json"
MANIFEST_SCHEMA = 3


class CacheError(Exception):
    pass


@dataclass(frozen=True)
class Recipe:
    name: str
    archive: str
    version: str
    rel: str
    directory: Path
    data: dict[str, Any]

    def split_archive(self, suffix: str) -> str:
        return f"{self.name}-{suffix}-{self.version}-{self.rel}.nawa.tar.zst"


def file_tree_hash(directory: Path) -> str:
    """Hash every file and relative path in a recipe directory, including assets."""
    digest = hashlib.sha256()
    for path in sorted(directory.rglob("*")):
        if not path.is_file() and not path.is_symlink():
            continue
        relative = path.relative_to(directory).as_posix().encode("utf-8")
        digest.update(relative)
        digest.update(b"\0")
        if path.is_symlink():
            payload = os.readlink(path).encode("utf-8")
        else:
            payload = path.read_bytes()
        digest.update(len(payload).to_bytes(8, "big"))
        digest.update(payload)
    return digest.hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_recipes(root: Path) -> dict[str, Recipe]:
    recipes: dict[str, Recipe] = {}
    for recipe_file in sorted(root.glob("*/*/recipe.toml")):
        try:
            data = tomllib.loads(recipe_file.read_text(encoding="utf-8"))
            package = data["package"]
            name = str(package["name"])
            version = str(package["version"])
            rel = str(package.get("rel", 1))
        except (OSError, KeyError, TypeError, tomllib.TOMLDecodeError) as exc:
            raise CacheError(f"cannot read package metadata from {recipe_file}: {exc}") from exc
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._+-]*", name):
            raise CacheError(f"unsafe package name in {recipe_file}: {name!r}")
        archive = f"{name}-{version}-{rel}.nawa.tar.zst"
        if not ARCHIVE_RE.fullmatch(archive):
            raise CacheError(f"unsafe archive name generated by {recipe_file}: {archive!r}")
        if name in recipes:
            raise CacheError(f"duplicate recipe name: {name}")
        recipes[name] = Recipe(name, archive, version, rel, recipe_file.parent, data)
    return recipes


def build_keys(recipes: dict[str, Recipe]) -> dict[str, str]:
    """Include the recipe tree and recursive build dependencies in each cache key."""
    memo: dict[str, str] = {}
    active: set[str] = set()

    def calculate(name: str) -> str:
        if name in memo:
            return memo[name]
        recipe = recipes.get(name)
        if recipe is None:
            return hashlib.sha256(f"external:{name}".encode("utf-8")).hexdigest()
        if name in active:
            # Recipe validation catches dependency cycles; keep cache calculation
            # deterministic rather than recursing forever if a broken tree appears.
            return hashlib.sha256(f"dependency-cycle:{name}".encode("utf-8")).hexdigest()

        active.add(name)
        digest = hashlib.sha256()
        digest.update(name.encode("utf-8"))
        digest.update(b"\0")
        digest.update(recipe.archive.encode("utf-8"))
        digest.update(b"\0")
        digest.update(file_tree_hash(recipe.directory).encode("ascii"))

        depends = recipe.data.get("depends", {})
        build_deps = depends.get("build", []) if isinstance(depends, dict) else []
        if isinstance(build_deps, str):
            build_deps = [build_deps]
        for dependency in sorted({str(item) for item in build_deps}):
            digest.update(b"\0build-dependency\0")
            digest.update(dependency.encode("utf-8"))
            digest.update(b"\0")
            digest.update(calculate(dependency).encode("ascii"))

        active.remove(name)
        memo[name] = digest.hexdigest()
        return memo[name]

    for name in sorted(recipes):
        calculate(name)
    return memo


def read_manifest(cache_dir: Path) -> list[dict[str, str]]:
    path = cache_dir / MANIFEST_NAME
    if not path.is_file():
        return []
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
        if value.get("schema") != MANIFEST_SCHEMA or not isinstance(value.get("packages"), list):
            raise ValueError("unsupported manifest schema")
        return value["packages"]
    except (OSError, ValueError, AttributeError, TypeError) as exc:
        print(f"::warning::ignoring invalid pull request package cache manifest: {exc}", file=sys.stderr)
        return []


def valid_entry(
    entry: dict[str, Any],
    recipes: dict[str, Recipe],
    keys: dict[str, str],
    cache_dir: Path,
    *,
    verify_digest: bool = True,
) -> tuple[Recipe, Path, list[tuple[str, Path]]] | None:
    name = entry.get("name")
    archive = entry.get("archive")
    key = entry.get("build_key")
    archive_sha256 = entry.get("archive_sha256")
    if (
        not isinstance(name, str)
        or not isinstance(archive, str)
        or not isinstance(key, str)
        or not isinstance(archive_sha256, str)
        or re.fullmatch(r"[0-9a-f]{64}", archive_sha256) is None
    ):
        return None
    if Path(archive).name != archive or not ARCHIVE_RE.fullmatch(archive):
        return None
    recipe = recipes.get(name)
    if recipe is None or recipe.archive != archive or keys.get(name) != key:
        return None
    cached = cache_dir / archive
    if not cached.is_file() or cached.stat().st_size == 0:
        return None
    if verify_digest and sha256_file(cached) != archive_sha256:
        return None

    split_archives = entry.get("split_archives", [])
    if not isinstance(split_archives, list):
        return None
    expected_splits = {recipe.split_archive("doc"), recipe.split_archive("lang")}
    checked_splits: list[tuple[str, Path]] = []
    seen_splits: set[str] = set()
    for split in split_archives:
        if not isinstance(split, dict):
            return None
        split_name = split.get("archive")
        split_digest = split.get("archive_sha256")
        if (
            not isinstance(split_name, str)
            or split_name not in expected_splits
            or split_name in seen_splits
            or not isinstance(split_digest, str)
            or re.fullmatch(r"[0-9a-f]{64}", split_digest) is None
        ):
            return None
        split_path = cache_dir / split_name
        if not split_path.is_file() or split_path.stat().st_size == 0:
            return None
        if verify_digest and sha256_file(split_path) != split_digest:
            return None
        seen_splits.add(split_name)
        checked_splits.append((split_name, split_path))
    return recipe, cached, checked_splits


def restore_cache(recipes_root: Path, cache_dir: Path, out_dir: Path) -> tuple[int, int]:
    recipes = load_recipes(recipes_root)
    keys = build_keys(recipes)
    cache_dir.mkdir(parents=True, exist_ok=True)
    out_dir.mkdir(parents=True, exist_ok=True)
    restored = 0
    rejected = 0

    for entry in read_manifest(cache_dir):
        checked = valid_entry(entry, recipes, keys, cache_dir)
        if checked is None:
            rejected += 1
            continue
        recipe, cached, splits = checked
        target = out_dir / recipe.archive
        if not target.exists():
            shutil.copy2(cached, target)
            restored += 1
        for split_name, split_path in splits:
            split_target = out_dir / split_name
            if not split_target.exists():
                shutil.copy2(split_path, split_target)

    return restored, rejected


def save_cache(
    recipes_root: Path,
    cache_dir: Path,
    out_dir: Path,
    since_file: Path,
    report_file: Path,
) -> tuple[int, int]:
    recipes = load_recipes(recipes_root)
    keys = build_keys(recipes)
    cache_dir.mkdir(parents=True, exist_ok=True)
    out_dir.mkdir(parents=True, exist_ok=True)
    try:
        since_ns = since_file.stat().st_mtime_ns
    except OSError as exc:
        raise CacheError(f"build start marker is missing: {since_file}") from exc

    entries: dict[str, dict[str, str]] = {}
    for entry in read_manifest(cache_dir):
        # Existing artifact digests are checked before restore/use. During a
        # continuation save we preserve their metadata without re-hashing every
        # potentially multi-gigabyte archive; the next restore is authoritative.
        checked = valid_entry(entry, recipes, keys, cache_dir, verify_digest=False)
        if checked is None:
            continue
        recipe, _, splits = checked
        entries[recipe.name] = {
            "name": recipe.name,
            "archive": recipe.archive,
            "build_key": keys[recipe.name],
            "archive_sha256": entry["archive_sha256"],
            "split_archives": [
                {"archive": split_name, "archive_sha256": split["archive_sha256"]}
                for split_name, split in (
                    (item["archive"], item) for item in entry.get("split_archives", [])
                )
            ],
        }

    try:
        report = report_file.read_text(encoding="utf-8")
    except OSError as exc:
        raise CacheError(f"build report is missing: {report_file}") from exc

    # Only packages that completed BOTH build and installation are reusable.
    # An archive can exist even when nawa fails while installing it.
    successfully_built = set(re.findall(r"^BUILT\s+([A-Za-z0-9][A-Za-z0-9._+-]*)\b", report, re.MULTILINE))
    by_archive = {recipe.archive: recipe for recipe in recipes.values()}

    added = 0
    for archive_name in sorted(by_archive):
        recipe = by_archive[archive_name]
        if recipe.archive.removesuffix(".nawa.tar.zst") not in successfully_built:
            continue
        archive_path = out_dir / recipe.archive
        if not archive_path.is_file() or archive_path.stat().st_size == 0:
            continue
        if archive_path.stat().st_mtime_ns <= since_ns:
            continue
        target = cache_dir / recipe.archive
        shutil.copy2(archive_path, target)
        split_entries: list[dict[str, str]] = []
        for suffix in ("doc", "lang"):
            split_name = recipe.split_archive(suffix)
            split_path = out_dir / split_name
            if (
                split_path.is_file()
                and split_path.stat().st_size > 0
                and split_path.stat().st_mtime_ns > since_ns
            ):
                split_target = cache_dir / split_name
                shutil.copy2(split_path, split_target)
                split_entries.append({
                    "archive": split_name,
                    "archive_sha256": sha256_file(split_target),
                })
        entries[recipe.name] = {
            "name": recipe.name,
            "archive": recipe.archive,
            "build_key": keys[recipe.name],
            "archive_sha256": sha256_file(target),
            "split_archives": split_entries,
        }
        added += 1

    live_archives = {
        archive
        for entry in entries.values()
        for archive in (
            [entry["archive"]]
            + [item["archive"] for item in entry.get("split_archives", [])]
        )
    }
    for cached in cache_dir.glob("*.nawa.tar.zst"):
        if cached.name not in live_archives:
            cached.unlink()

    manifest = {
        "schema": MANIFEST_SCHEMA,
        "packages": [entries[name] for name in sorted(entries)],
    }
    temp = cache_dir / f".{MANIFEST_NAME}.tmp"
    temp.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    temp.replace(cache_dir / MANIFEST_NAME)
    return added, len(entries)


def invalidate_relation_archives(
    recipes_root: Path,
    out_dir: Path,
    names: list[str],
) -> int:
    """Remove old published-format archives for selected relation-bearing recipes.

    A v3 archive may have the same filename as a v5 rebuild. Leaving it in the
    build output causes build-packages-inner.sh to treat it as current and skip
    the rebuild, so selected relation recipes must be invalidated before cache
    restoration and build planning.
    """
    selected = set(names)
    if not selected:
        return 0
    removed = 0
    for recipe_file in sorted(recipes_root.glob("*/*/recipe.toml")):
        try:
            data = tomllib.loads(recipe_file.read_text(encoding="utf-8"))
            package = data["package"]
            name = str(package["name"])
            version = str(package["version"])
            rel = str(package.get("rel", 1))
        except (OSError, KeyError, TypeError, tomllib.TOMLDecodeError) as exc:
            raise CacheError(f"cannot read package metadata from {recipe_file}: {exc}") from exc
        if name not in selected or "relations" not in data:
            continue
        identities = [
            f"{name}-{version}-{rel}.nawa.tar.zst",
            f"{name}-doc-{version}-{rel}.nawa.tar.zst",
            f"{name}-lang-{version}-{rel}.nawa.tar.zst",
        ]
        for filename in identities:
            path = out_dir / filename
            if path.is_file():
                path.unlink()
                print(f"invalidated legacy archive for schema-v5 rebuild: {filename}")
                removed += 1
    unknown = selected - {
        tomllib.loads(path.read_text(encoding="utf-8"))["package"]["name"]
        for path in recipes_root.glob("*/*/recipe.toml")
    }
    if unknown:
        raise CacheError("selected package(s) have no recipe: " + ", ".join(sorted(unknown)))
    return removed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("restore", "save"):
        command = sub.add_parser(name)
        command.add_argument("--recipes", type=Path, required=True)
        command.add_argument("--cache-dir", type=Path, required=True)
        command.add_argument("--out-dir", type=Path, required=True)
        if name == "save":
            command.add_argument("--since", type=Path, required=True)
            command.add_argument("--report", type=Path, required=True)
    invalidate = sub.add_parser("invalidate-relations")
    invalidate.add_argument("--recipes", type=Path, required=True)
    invalidate.add_argument("--out-dir", type=Path, required=True)
    invalidate.add_argument("--names", default="")
    args = parser.parse_args(argv)

    try:
        if args.command == "restore":
            restored, rejected = restore_cache(args.recipes, args.cache_dir, args.out_dir)
            print(f"PR package cache: restored {restored} archive(s); rejected {rejected} stale or invalid entrie(s).")
        elif args.command == "save":
            added, total = save_cache(args.recipes, args.cache_dir, args.out_dir, args.since, args.report)
            print(f"PR package cache: saved {added} new archive(s); {total} reusable archive(s) retained.")
        else:
            removed = invalidate_relation_archives(args.recipes, args.out_dir, args.names.split())
            print(f"Invalidated {removed} legacy archive(s) for selected schema-v5 package(s).")
        return 0
    except (CacheError, OSError) as exc:
        print(f"::error::PR package cache: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
